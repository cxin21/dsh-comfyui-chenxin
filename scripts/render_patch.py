#!/usr/bin/env python3
"""Generate cordis.patch.yml's deployment paths for THIS checkout.

Why this exists
---------------
``agent.cordis.yml`` is the portable, human-editable source: its two local
plugin entries are written ``./loader.js`` / ``./plugins/prompt-forge/...``
with ``presetRoot: null``. ``cordis.patch.yml`` is what DSH actually loads,
and it must differ in exactly three values:

  * ``comfyui-loader.name``       ``./loader.js`` -> ``file:///<checkout>/loader.js``
  * ``comfyui-loader.config.presetRoot``  ``null`` -> ``<checkout>``
  * ``prompt-forge.name``         ``./plugins/...`` -> ``file:///<checkout>/plugins/...``

Those are not cosmetic. DSH imports a preset's nested plugin entries from a
**host-side base** (the asar copy of ``@deepseek-ai/dsh-agent-preset`` /
``dsh-app-boot``), not from the profile directory. From that base:

  * ``file:///<abs>`` resolves everywhere;
  * ``@local/<pkg>/<subpath>`` raises ERR_MODULE_NOT_FOUND (only the profile's
    node_modules has ``@local``);
  * ``./...`` is not anchored by ``anchorInsertedPluginNames`` because the
    preset row is a plain-object config, not a group with an array config.

`cordis-plugin-loader`'s Entry._init() swallows the import error and leaves
``fiber === undefined``; the preset registry then reports ``never started``
and the UI treats the whole preset as absent. (See KNOWN-ISSUES #28/#29.)

So the deployment form *must* carry absolute paths. Hard-coding one machine's
path in git is what broke portability (#26). This script is the reconciliation:
the absolute paths are derived from the checkout this script lives in, so setup
on each machine regenerates the patch for that machine. The committed patch is
simply the last generated form and is re-generated by ``scripts/setup.*``.

Only the three values above are touched; every comment and every other line in
``cordis.patch.yml`` is preserved verbatim.

Usage:  python scripts/render_patch.py [--checkout PATH]
Exit:   0 = patch rewritten (or already correct), 1 = source/patch malformed.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

try:
    import yaml
except ImportError:  # pragma: no cover - environment guard
    print("FAIL: PyYAML is required", file=sys.stderr)
    raise SystemExit(1)

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "agent.cordis.yml"
PATCH = ROOT / "cordis.patch.yml"

PRESET_ENTRY_ID = "preset-comfyui-chenxin"
# Entries whose deployment `name` becomes an absolute file:/// URL.
ABSOLUTE_PATH_ENTRIES = {"comfyui-loader", "prompt-forge"}
PINNED_ROOT_ENTRY = "comfyui-loader"


def file_url(path: Path) -> str:
    """``D:\\x\\loader.js`` -> ``file:///D:/x/loader.js``."""
    return "file:///" + path.resolve().as_posix().lstrip("/")


def load_source_names() -> dict[str, str]:
    """Map the two local entry ids to their portable ``./`` source names."""
    doc = yaml.safe_load(SOURCE.read_text(encoding="utf-8"))
    if not isinstance(doc, list):
        raise SystemExit(f"FAIL: {SOURCE.name} must be a flat list of entries")
    names: dict[str, str] = {}
    for entry in doc:
        if not isinstance(entry, dict):
            continue
        eid = entry.get("id")
        if eid in ABSOLUTE_PATH_ENTRIES:
            name = entry.get("name")
            if not isinstance(name, str) or not name.startswith("./"):
                raise SystemExit(
                    f"FAIL: {SOURCE.name} entry {eid!r} must have a ./-relative "
                    f"name, got {name!r}"
                )
            names[eid] = name
    missing = ABSOLUTE_PATH_ENTRIES - names.keys()
    if missing:
        raise SystemExit(f"FAIL: missing source entries: {sorted(missing)}")
    return names


def render(checkout: Path) -> None:
    names = load_source_names()
    checkout = checkout.resolve()
    lines = PATCH.read_text(encoding="utf-8").splitlines(keepends=True)

    current_id: str | None = None
    changed: dict[str, str] = {}
    for i, line in enumerate(lines):
        m = re.match(r"^(\s*)- id:\s*(\S+)\s*$", line)
        if m:
            current_id = m.group(2)
            continue
        if current_id not in ABSOLUTE_PATH_ENTRIES:
            continue

        nm = re.match(r"^(\s*)name:\s*\S.*$", line)
        if nm and current_id in names:
            rel = names[current_id][2:]  # strip leading "./"
            lines[i] = f"{nm.group(1)}name: '{file_url(checkout / rel)}'\n"
            changed[f"{current_id}.name"] = lines[i].strip()
            continue

        if current_id == PINNED_ROOT_ENTRY:
            rm = re.match(r"^(\s*)presetRoot:\s*\S.*$", line)
            if rm:
                lines[i] = f"{rm.group(1)}presetRoot: '{checkout.as_posix()}'\n"
                changed[f"{current_id}.presetRoot"] = lines[i].strip()

    absent = set(changed) - {
        "comfyui-loader.name", "comfyui-loader.presetRoot", "prompt-forge.name"
    }
    if absent:
        raise SystemExit(f"FAIL: unexpected rewrites: {sorted(absent)}")
    if len(changed) != 3:
        raise SystemExit(
            f"FAIL: expected 3 deployment values in {PATCH.name}, rewrote {len(changed)}: "
            f"{sorted(changed)}"
        )

    PATCH.write_text("".join(lines), encoding="utf-8")
    print(f"[render_patch] checkout: {checkout}")
    for key in sorted(changed):
        print(f"[render_patch] {key} = {changed[key]}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--checkout", type=Path, default=ROOT,
        help="checkout to pin (default: this script's parent directory)",
    )
    args = parser.parse_args()
    render(args.checkout)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
